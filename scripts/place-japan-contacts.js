// Anchor fictional contacts to real public road nodes. IDs remain stable for
// existing story saves; airport positions use actual terminal landside areas.
import fs from 'node:fs';
import {Network} from '../src/network.js';
import {distance} from '../src/geo.js';
const targets={
 osaka:[[135.500,34.701],[135.508,34.702],[135.505,34.692],[135.493,34.696],[135.485,34.704],[135.441,34.7896],[135.492,34.710],[135.515,34.695],[135.497,34.685]],
 tokyo:[[139.740,35.628],[139.748,35.630],[139.744,35.620],[139.731,35.622],[139.730,35.633],[139.782,35.5495],[139.738,35.638],[139.755,35.620],[139.730,35.613]]
};
const neighbourhoods={osaka:['Umeda','Tenma','Nakanoshima','Fukushima','Noda','Itami Airport (ITM) · landside terminal','Nakatsu','Kitahama','Honmachi'],tokyo:['Shinagawa','Konan','Kitashinagawa','Gotanda','Takanawa','Haneda Airport (HND) · Terminal 1 landside','Sengakuji','Tennozu','Osaki']};
const labels=['reception','records contact','dispatch desk','shelter','supply exchange','air terminal','cash contact','rest garden','final pickup'];
const output={};
function largestComponent(network,bit){
 const seen=new Set(),order=[],reverse=new Map();
 for(const [id,n] of network.nodes)for(const e of n.edges)if(e.mask&bit){if(!reverse.has(e.to))reverse.set(e.to,[]);reverse.get(e.to).push(id);}
 for(const [root,n] of network.nodes){if(!(n.mask&bit)||seen.has(root))continue;seen.add(root);const stack=[[root,0]];
  while(stack.length){const entry=stack.at(-1),edges=network.nodes.get(entry[0]).edges;let next;
   while(entry[1]<edges.length){const e=edges[entry[1]++];if(e.mask&bit&&!seen.has(e.to)){next=e.to;break;}}
   if(next){seen.add(next);stack.push([next,0]);}else{order.push(entry[0]);stack.pop();}
  }
 }
 seen.clear();let largest=[];
 for(const root of order.reverse()){if(seen.has(root))continue;const component=[],stack=[root];seen.add(root);while(stack.length){const id=stack.pop();component.push(id);for(const next of reverse.get(id)||[])if(!seen.has(next)){seen.add(next);stack.push(next);}}if(component.length>largest.length)largest=component;}
 return new Set(largest);
}
for(const [h,city] of ['osaka','tokyo'].entries()){
 const network=new Network(JSON.parse(fs.readFileSync(new URL(`../public/data/${city}.geojson`,import.meta.url))));
 const motor=largestComponent(network,4),foot=largestComponent(network,1);console.log(city,'connected public components',motor.size,foot.size);
 const used=new Set(),points=[];
 for(const [j,target] of targets[city].entries()){
  const candidates=[...network.nodes].filter(([id,n])=>(n.mask&5)===5&&motor.has(id)&&foot.has(id)&&!used.has(id)).map(([id,n])=>({id,coordinates:n.p,km:distance(target,n.p)})).sort((a,b)=>a.km-b.km).slice(0,50);
  const chosen=candidates.find(p=>!points.length||['walk','taxi','bus'].every(mode=>network.route(points[0],{...p,kind:j===5?'airport':'supply'},mode)&&network.route({...p,id:'return-'+p.id,kind:'supply'},points[0],mode)));
  if(!chosen||chosen.km>.5)throw Error('No nearby connected public road anchor for '+city+' '+j);
  used.add(chosen.id);const id=`world-0-${h}-${j}`;points.push({id,coordinates:chosen.coordinates});
  output[id]={coordinates:chosen.coordinates,anchorNode:chosen.id,name:(city==='osaka'?'Osaka':'Tokyo')+' · '+(j===5?neighbourhoods[city][j]:neighbourhoods[city][j]+' '+labels[j]),district:neighbourhoods[city][j],mapPack:city};
 }
 console.log(city,network.stats,points.length+' connected contacts, including '+output[`world-0-${h}-5`].name);
}
fs.writeFileSync(new URL('../src/japan-places.js',import.meta.url),'// Generated by scripts/place-japan-contacts.js from the attributed OSM map packs.\nexport const JAPAN_PLACES=Object.freeze('+JSON.stringify(output,null,1)+');\n');
